CREATE TABLE IF NOT EXISTS `business_audit_event` (
  `event_id` char(36) NOT NULL,
  `occurred_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `actor_subject` varchar(64) DEFAULT NULL,
  `actor_username` varchar(100) DEFAULT NULL,
  `actor_roles` json DEFAULT NULL,
  `source` varchar(32) NOT NULL DEFAULT 'ERP_UI',
  `action` varchar(128) NOT NULL,
  `resource_type` varchar(64) DEFAULT NULL,
  `resource_id` varchar(191) DEFAULT NULL,
  `request_id` varchar(64) NOT NULL,
  `trace_id` varchar(64) DEFAULT NULL,
  `operation_id` varchar(128) DEFAULT NULL,
  `http_method` varchar(16) DEFAULT NULL,
  `request_path` varchar(500) DEFAULT NULL,
  `outcome` varchar(32) NOT NULL,
  `status_code` int DEFAULT NULL,
  `changed_fields` json DEFAULT NULL,
  `before_json` json DEFAULT NULL,
  `after_json` json DEFAULT NULL,
  `error_code` varchar(64) DEFAULT NULL,
  `error_message` varchar(500) DEFAULT NULL,
  `client_ip` varchar(64) DEFAULT NULL,
  `user_agent` varchar(500) DEFAULT NULL,
  PRIMARY KEY (`event_id`),
  KEY `idx_business_audit_actor_time` (`actor_subject`, `occurred_at` DESC),
  KEY `idx_business_audit_resource` (`resource_type`, `resource_id`, `occurred_at` DESC),
  KEY `idx_business_audit_operation` (`operation_id`),
  KEY `idx_business_audit_request` (`request_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

